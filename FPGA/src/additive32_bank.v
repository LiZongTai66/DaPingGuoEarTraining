`timescale 1ns/1ps
// 4 spatial arithmetic lanes x 8 batches = 32 additive harmonics per voice.
// All 15 voices computed in 406 clocks; input period is 576 clocks at 27MHz.
// Per voice: y = sum(sin(h*phase)*weight[h]) * envelope / 2^22.
module additive32_bank(input clk,input sample_tick,
 input [479:0] phase_bus,phase2_bus,inc_bus,input [239:0] env_bus,
 input [14:0] guitar_bus,active_bus,output reg [359:0] audio_bus=0,
