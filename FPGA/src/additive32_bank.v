 localparam IDLE=0,LOAD=1,LOOKUP=2,MULTIPLY=3,ACCUMULATE=4,SCALE=5,STORE=6,PUBLISH=7;
 reg [2:0] state=IDLE;
 assign busy=(state!=IDLE);
 reg [3:0] voice=0;reg [2:0] batch=0;
 reg [31:0] phases[0:14],phases2[0:14],incs[0:14];reg [15:0] envs[0:14];
 reg [14:0] guitars=0,actives=0;
 reg [359:0] pending=0;
 reg [31:0] lane_phase[0:3],phase_step=0;
 reg [36:0] lane_inc[0:3],inc_step=0;
 wire signed [11:0] sine_reg[0:3];reg [9:0] weight_reg[0:3];
 reg signed [22:0] product[0:3];
 reg signed [27:0] total=0;reg signed [15:0] guitar_mix=0;
 reg signed [44:0] scaled=0;
 reg [15:0] envelope=0;reg instrument=0,enabled=0;
 function [9:0] weight;input [5:0] h;input guitar;begin case(h)
 6'd1:weight = guitar ? 10'd512 : 10'd512;
 6'd2:weight = guitar ? 10'd160 : 10'd96;
 6'd3:weight = guitar ? 10'd88 : 10'd40;
 6'd4:weight = guitar ? 10'd48 : 10'd24;
 6'd5:weight = guitar ? 10'd32 : 10'd14;
 6'd6:weight = guitar ? 10'd24 : 10'd10;
 6'd7:weight = guitar ? 10'd16 : 10'd7;
 6'd8:weight = guitar ? 10'd12 : 10'd5;
 6'd9:weight = guitar ? 10'd9 : 10'd4;
 6'd10:weight = guitar ? 10'd7 : 10'd3;
 6'd11:weight = guitar ? 10'd6 : 10'd3;
 6'd12:weight = guitar ? 10'd5 : 10'd2;
 6'd13:weight = guitar ? 10'd4 : 10'd2;
 6'd14:weight = guitar ? 10'd3 : 10'd2;
 6'd15:weight = guitar ? 10'd3 : 10'd1;
 6'd16:weight = guitar ? 10'd2 : 10'd1;
 6'd17:weight = guitar ? 10'd2 : 10'd1;
 6'd18:weight = guitar ? 10'd2 : 10'd1;
 6'd19:weight = guitar ? 10'd2 : 10'd1;
 6'd20:weight = guitar ? 10'd1 : 10'd1;
 6'd21:weight = guitar ? 10'd1 : 10'd1;
 6'd22:weight = guitar ? 10'd1 : 10'd1;
 6'd23:weight = guitar ? 10'd1 : 10'd1;
 6'd24:weight = guitar ? 10'd1 : 10'd1;
 6'd25:weight = guitar ? 10'd1 : 10'd1;
 6'd26:weight = guitar ? 10'd1 : 10'd1;
 6'd27:weight = guitar ? 10'd1 : 10'd1;
 6'd28:weight = guitar ? 10'd1 : 10'd1;
 6'd29:weight = guitar ? 10'd1 : 10'd1;
 6'd30:weight = guitar ? 10'd1 : 10'd1;
 6'd31:weight = guitar ? 10'd1 : 10'd1;
 6'd32:weight = guitar ? 10'd1 : 10'd1;
 default:weight=0;endcase end endfunction
 wire signed [27:0] batch_sum=
  $signed({{5{product[0][22]}},product[0]})+
  $signed({{5{product[1][22]}},product[1]})+
  $signed({{5{product[2][22]}},product[2]})+
  $signed({{5{product[3][22]}},product[3]});
genvar lane;
 generate for(lane=0;lane<4;lane=lane+1)begin:sine_lanes
 additive32_sine_rom sine_rom(.clk(clk),.addr({instrument,lane_phase[lane][31:24]}),.q(sine_reg[lane]));
 end endgenerate

 integer i;
 always @(posedge clk)begin
  frame_done<=0;
  if(sample_tick && busy)overrun<=1;
  case(state)
   IDLE:if(sample_tick)begin
    for(i=0;i<15;i=i+1)begin
     phases[i]<=phase_bus[i*32+:32];phases2[i]<=phase2_bus[i*32+:32];incs[i]<=inc_bus[i*32+:32];envs[i]<=env_bus[i*16+:16];
    end
    guitars<=guitar_bus;actives<=active_bus;voice<=0;state<=LOAD;
   end
   LOAD:begin
    if(guitars[voice])begin
     lane_phase[0]<=phases[voice];lane_phase[1]<=phases2[voice];
     lane_phase[2]<=phases[voice]<<1;lane_phase[3]<=phases[voice]+(phases[voice]<<1);
    end else begin
     lane_phase[0]<=phases[voice];lane_phase[1]<=phases[voice]<<1;
     lane_phase[2]<=phases[voice]+(phases[voice]<<1);lane_phase[3]<=phases[voice]<<2;
    end
    lane_inc[0]<={5'd0,incs[voice]};lane_inc[1]<={5'd0,incs[voice]}<<1;
    lane_inc[2]<={5'd0,incs[voice]}+({5'd0,incs[voice]}<<1);
    lane_inc[3]<={5'd0,incs[voice]}<<2;
    phase_step<=phases[voice]<<2;inc_step<={5'd0,incs[voice]}<<2;
    envelope<=envs[voice];instrument<=guitars[voice];enabled<=actives[voice];
    batch<=0;total<=0;state<=LOOKUP;
   end
   LOOKUP:begin
    for(i=0;i<4;i=i+1)begin

     // Wide increment prevents wrapped upper harmonics from passing Nyquist.
     weight_reg[i]<=(enabled && lane_inc[i]!=0 && lane_inc[i]<37'd2147483648)?
       weight(({3'd0,batch}<<2)+i+1,instrument):10'd0;
     lane_phase[i]<=lane_phase[i]+phase_step;lane_inc[i]<=lane_inc[i]+inc_step;
    end
    state<=MULTIPLY;
   end
   MULTIPLY:begin
    // ROM page1 is exactly donor sine64 *16. Shift before summation matches
    // donor arithmetic rounding: s1/2+s2/2+h2/2+h3/4.
    guitar_mix<=($signed(sine_reg[0])>>>5)+($signed(sine_reg[1])>>>5)+
                ($signed(sine_reg[2])>>>5)+($signed(sine_reg[3])>>>6);
    for(i=0;i<4;i=i+1)product[i]<=sine_reg[i]*$signed({1'b0,weight_reg[i]});
    state<=ACCUMULATE;
   end
   ACCUMULATE:begin
    if(instrument)begin
     if(batch==0)total<=enabled?$signed(guitar_mix):28'sd0;
    end else total<=total+batch_sum;
    if(batch==7)state<=SCALE;else begin batch<=batch+1'b1;state<=LOOKUP;end
   end
   SCALE:begin scaled<=total*$signed({1'b0,envelope});state<=STORE;end
   STORE:begin
    pending[voice*24+:24]<=instrument?(scaled>>>9):(scaled>>>22);
    if(voice==14)state<=PUBLISH;else begin voice<=voice+1'b1;state<=LOAD;end
   end
   PUBLISH:begin audio_bus<=pending;frame_done<=1;state<=IDLE;end
   default:state<=IDLE;
  endcase
 end
endmodule

